// Renders the declarative policy set from the model, so the checked-in file
// and the thing the tests exercise cannot drift apart.
//
//   node scripts/render-policies.ts          # write
//   node scripts/render-policies.ts --check  # fail if the file is stale

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { pavedZone } from "../src/scenarios.ts";

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, "..", "policies", "landing-zone.json");

export function render(): string {
  const h = pavedZone().hierarchy;
  const doc = {
    $comment:
      "Generated by scripts/render-policies.ts from src/scenarios.ts. Do not edit by hand.",
    nodes: [...h.nodes()]
      .map((n) => ({ id: n.id, kind: n.kind, parent: n.parent }))
      .sort((a, b) => a.id.localeCompare(b.id)),
    policies: [...h.policies()]
      .map((p) => ({
        constraint: p.constraint,
        node: p.nodeId,
        value: p.value,
        expiresAtMs: p.expiresAtMs,
        justification: p.justification ?? null,
      }))
      .sort((a, b) => `${a.node}/${a.constraint}`.localeCompare(`${b.node}/${b.constraint}`)),
    grants: [...h.grants()]
      .map((g) => ({
        principal: g.principal,
        role: g.role,
        scope: g.scope,
        serviceAccount: g.serviceAccount ?? null,
        expiresAtMs: g.expiresAtMs,
        justification: g.justification ?? null,
      }))
      .sort((a, b) =>
        `${a.principal}/${a.scope}/${a.role}`.localeCompare(`${b.principal}/${b.scope}/${b.role}`),
      ),
  };
  return JSON.stringify(doc, null, 2) + "\n";
}

const rendered = render();

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {
    console.error("policies/landing-zone.json is missing; run: node scripts/render-policies.ts");
    process.exit(1);
  }
  if (current !== rendered) {
    console.error("policies/landing-zone.json is stale; run: node scripts/render-policies.ts");
    process.exit(1);
  }
  console.log("policies: up to date");
} else {
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, rendered);
  console.log("wrote policies/landing-zone.json");
}
