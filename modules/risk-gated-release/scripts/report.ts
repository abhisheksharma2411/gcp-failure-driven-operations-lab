// Emits the manifest as a machine-readable artifact plus a readable matrix.
// The article quotes results/; never edit it by hand.
import { writeFileSync } from "node:fs";
import { ALL_RADII, ALL_TYPES, emergencyGates, requiredGates } from "../src/manifest.ts";
import { evaluate } from "../src/evaluate.ts";
import { rollout, ungatedRollout, type Baseline, type Observation } from "../src/rollout.ts";
import type { Change } from "../src/types.ts";

// 1. The manifest itself, as data a pipeline could consume.
const manifest = {
  version: 1,
  description:
    "Required release gates derived from change type and blast radius. " +
    "No change type is exempt; scrutiny follows reach.",
  emergency_path: emergencyGates(),
  matrix: Object.fromEntries(
    ALL_TYPES.map((type) => [
      type,
      Object.fromEntries(ALL_RADII.map((radius) => [radius, requiredGates(type, radius)])),
    ]),
  ),
};
writeFileSync("results/release-risk-manifest.json", JSON.stringify(manifest, null, 2));

// 2. The exposure comparison the article quotes.
const BASELINE: Baseline = { errorRate: 0.001, p99Ms: 200 };
const ok: Observation = { errorRate: 0.001, p99Ms: 200, businessCheckPassed: true };
const gated: Change = {
  id: "demo", type: "edge-policy", radius: "global",
  satisfied: requiredGates("edge-policy", "global"),
  promotedBy: "release-pipeline@example",
};
const ungated: Change = { ...gated, satisfied: ["AUDIT_IDENTITY"] };

const scenarios = {
  "gated, healthy": rollout(gated, BASELINE, () => ok),
  "gated, error-rate regression at 25%": rollout(gated, BASELINE, (p) =>
    p.name === "canary-25" ? { ...ok, errorRate: 1 } : ok),
  "gated, business check fails at 25%": rollout(gated, BASELINE, (p) =>
    p.name === "canary-25" ? { ...ok, businessCheckPassed: false } : ok),
  "manifest blocks the ungated change": rollout(ungated, BASELINE, () => ok),
  "no manifest at all, broken change": ungatedRollout(BASELINE, () => ({ ...ok, errorRate: 1 })),
};
writeFileSync("results/scenarios.json", JSON.stringify(scenarios, null, 2));

const rows: string[] = [];
rows.push("# Release-risk results\n");
rows.push("Generated by `make report`. Deterministic; no cloud project, no network.\n");
rows.push("## Required gates by change type and blast radius\n");
rows.push("| Change type | single-instance | single-region | global |");
rows.push("|---|---:|---:|---:|");
for (const type of ALL_TYPES) {
  const cells = ALL_RADII.map((r) => requiredGates(type, r).length);
  rows.push(`| \`${type}\` | ${cells[0]} | ${cells[1]} | ${cells[2]} |`);
}
rows.push("\nGate counts, not names, so the shape is visible. Full sets are in");
rows.push("`results/release-risk-manifest.json`. Every type at global radius carries the");
rows.push("same seven core gates; schema, IAM and edge-policy add a compatibility check.\n");

rows.push("## Exposure under failure\n");
rows.push("| Scenario | Outcome | Reached phase | Max traffic exposed |");
rows.push("|---|---|---|---:|");
for (const [name, r] of Object.entries(scenarios)) {
  rows.push(`| ${name} | ${r.outcome} | ${r.reachedPhase ?? "none"} | ${r.maxExposure}% |`);
}
rows.push("\nRow three is the manifest doing its job: the change never reaches traffic at all.");
rows.push("Row four is the 2019 shape, and it needs the gate to be ABSENT rather than failed --");
rows.push("running an ungated change through the gated path just gets it blocked, which is the");
rows.push("manifest working. Without any gate, the regression is detected after everything is");
rows.push("already exposed.\n");

rows.push("## Audit records are produced on both paths\n");
const blocked = evaluate(ungated);
rows.push("```json");
rows.push(JSON.stringify(blocked.audit, null, 2));
rows.push("```");

writeFileSync("results/report.md", rows.join("\n") + "\n");
console.log(rows.join("\n"));
