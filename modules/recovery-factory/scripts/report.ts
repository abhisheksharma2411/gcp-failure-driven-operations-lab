import { writeFileSync } from "node:fs";
import { makeDataset, dropOneLeg } from "../src/ledger.ts";
import { attemptDelete, setRetention, takeBackup } from "../src/protection.ts";
import { restore } from "../src/restore.ts";
import { DAY, GOOD_TOOL, KEY, STALE_TOOL, loadManifest } from "../src/scenarios.ts";

const manifest = loadManifest();
const source = makeDataset(500);
const head = 500 * 1000;
const captured = head - 4 * 3_600_000; // captured four hours before head
const now = head + 60_000;

const rows: string[] = [];
const all: Record<string, unknown> = {};

const run = (name: string, ev: ReturnType<typeof restore>) => {
  all[name] = ev;
  rows.push(
    `| ${name} | \`${ev.outcome}\` | ${ev.stepsCompleted.length}/7 | ` +
    `${(ev.rtoMs / 60000).toFixed(0)} min | ${(ev.rpoMs / 3600000).toFixed(1)} h | ` +
    `${ev.invariants.filter((i) => !i.passed).length} |`,
  );
};

rows.push("# Recovery factory results\n");
rows.push("Generated by `make report`. No cloud project, no credentials, no network.\n");
rows.push("All figures are **simulated results**. RTO and RPO are measured inside the model");
rows.push("and are not vendor figures or targets.\n");
rows.push("| Scenario | Outcome | Steps | RTO | RPO | Failed invariants |");
rows.push("|---|---|---:|---:|---:|---:|");

// 1. Healthy restore.
const good = takeBackup("bk-good", source, { ...GOOD_TOOL, keyRef: KEY, atMs: captured, retentionDays: 30, retentionLocked: true });
run("healthy restore", restore(good, manifest, { sourceHeadMs: head, nowMs: now }));

// 2. The 2017 failure: job ran, output unusable.
const stale = takeBackup("bk-stale", source, { ...STALE_TOOL, keyRef: KEY, atMs: captured, retentionDays: 30, retentionLocked: true });
run("backup job succeeded, output unusable", restore(stale, manifest, { sourceHeadMs: head, nowMs: now }));

// 3. Key destroyed.
run("encryption key unavailable", restore(good, { ...manifest, availableKeys: [] }, { sourceHeadMs: head, nowMs: now }));

// 4. Undeclared dependency in the manifest.
run("manifest omits a dependency", restore(good, {
  ...manifest,
  steps: [...manifest.steps, { id: "app-config", description: "app config", requires: ["secrets-vault"] }],
}, { sourceHeadMs: head, nowMs: now }));

// 5. Restore succeeds, ledger is wrong.
const corrupt = takeBackup("bk-corrupt", dropOneLeg(source), { ...GOOD_TOOL, keyRef: KEY, atMs: captured, retentionDays: 30, retentionLocked: true });
run("restore completes, invariants fail", restore(corrupt, manifest, { sourceHeadMs: head, nowMs: now }));

// 6. A compromised identity tries to destroy the evidence.
const locked = takeBackup("bk-locked", source, { ...GOOD_TOOL, keyRef: KEY, atMs: captured, retentionDays: 30, retentionLocked: true });
const del = attemptDelete(locked, now);
const shorten = setRetention(locked, now);
run("after a hostile delete attempt", restore(locked, manifest, { sourceHeadMs: head, nowMs: now }));

rows.push("");
rows.push("## Protection against the operator\n");
rows.push("| Action by a fully privileged identity | Result |");
rows.push("|---|---|");
rows.push(`| delete the locked artifact | \`${del}\` |`);
rows.push(`| shorten its retention | ${shorten.applied ? "applied" : `refused — ${shorten.reason}`} |`);
rows.push(`| artifact state afterwards | \`${locked.state}\` |`);
rows.push("");
rows.push("Modelled on a locked retention policy, which \"cannot be removed or reduced\".");
rows.push("Protection is a ratchet: extending retention is always allowed, shortening never is.\n");

all["protection"] = { deleteOutcome: del, shorten, finalState: locked.state };
writeFileSync("results/recovery.json", JSON.stringify(all, null, 2));
writeFileSync("results/report.md", rows.join("\n") + "\n");
console.log(rows.join("\n"));
