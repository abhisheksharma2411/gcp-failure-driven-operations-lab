// Runs the fault catalogue and writes results/ deterministically.
//
//   node scripts/report.ts
//
// No cloud project, no credentials, no network. Re-running produces
// byte-identical output: there is no Date.now() anywhere in src/, and every
// identifier is derived from a seeded counter.

import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { SCENARIOS, MUTATIONS, BLUNT_MUTATION, runCatalogue, canaryForReport, T0 } from "../src/scenarios.ts";
import { ALERTS } from "../src/alerts.ts";
import { INVARIANTS } from "../src/invariants.ts";
import { SLOS, invariantsWithoutSlo } from "../src/slo.ts";
import { catalogueCardinality, totalDeclaredSeries } from "../src/signals.ts";
import { summariseVolume, DEFAULT_ASSUMPTIONS } from "../src/cost.ts";
import { metricsOnNoDashboard, DASHBOARDS } from "../src/dashboard.ts";
import { respond } from "../src/incident.ts";
import { Pipeline } from "../src/domain/flow.ts";
import { DEFAULT_BUDGETS } from "../src/domain/types.ts";

const HERE = dirname(fileURLToPath(import.meta.url));
const RESULTS = join(HERE, "..", "results");
mkdirSync(RESULTS, { recursive: true });

// --- E1: the fault catalogue ------------------------------------------------

const results = runCatalogue();

// --- E2: the green-and-wrong count -----------------------------------------

const greenAndWrong = results.filter((r) => r.technicalGreen && r.invariantsViolated.length > 0);
const greenAndSilent = results.filter(
  (r) => r.technicalGreen && r.invariantsViolated.length === 0 && r.alertsFired.length > 0,
);

// --- E3: negative controls --------------------------------------------------

const controls = MUTATIONS.map((m) => {
  const failed = runCatalogue(m).filter((r) => !r.passed);
  return {
    removed: m,
    scenariosTurnedRed: failed.map((f) => f.id),
    detected: failed.length > 0,
    targeted: failed.length > 0 && failed.length <= SCENARIOS.length / 2,
  };
});

const blunt = runCatalogue(BLUNT_MUTATION).filter((r) => !r.passed);
const bluntControl = {
  removed: BLUNT_MUTATION,
  scenariosTurnedRed: blunt.map((f) => f.id),
  rejected: blunt.length > SCENARIOS.length / 2,
  reason: "a mutation that reddens most of the catalogue cannot show which scenario covers which layer",
};

// --- E4: alert coverage -----------------------------------------------------

const firedAnywhere = new Set(results.flatMap((r) => r.alertsFired));
const neverFired = ALERTS.filter((a) => !firedAnywhere.has(a.id)).map((a) => a.id);
const scenariosWithoutAlert = results
  .filter((r) => r.alertsFired.length === 0 && r.invariantsViolated.length > 0)
  .map((r) => r.id);

// --- E5: one incident, end to end ------------------------------------------

const incidentPipeline = new Pipeline({ seed: 2206, samplingRate: 1 });
incidentPipeline.submit(
  { operationId: "op-2206", businessRef: "order-2206", amountMinor: 50_000, currency: "EUR" },
  T0,
  { dropFeeLeg: true },
);
const evidence = respond({
  alertId: "ALERT-LEDGER-IMBALANCE",
  world: incidentPipeline.world,
  audit: incidentPipeline.audit,
  budgets: DEFAULT_BUDGETS,
  firedAtMs: T0 + 10 * 60_000,
});

// --- E6: canary, cardinality, volume ---------------------------------------

const canary = canaryForReport();
const cardinality = catalogueCardinality();
const volume = summariseVolume();

// --- write ------------------------------------------------------------------

const payload = {
  generatedFrom: "scripts/report.ts",
  evaluatedAt: new Date(T0).toISOString(),
  note: "Deterministic. No cloud project, no credentials, no network. Every figure is a Simulated result.",
  scenarios: results,
  greenAndWrong: greenAndWrong.map((r) => r.id),
  negativeControls: controls,
  bluntControl,
  alertCoverage: { neverFired, scenariosWithoutAlert },
  incident: evidence,
  canary,
  cardinality: { perMetric: cardinality, totalDeclaredSeries: totalDeclaredSeries() },
  telemetryVolume: { assumptions: DEFAULT_ASSUMPTIONS, summary: volume },
  sloCoverage: { invariantsWithoutSlo: invariantsWithoutSlo() },
  dashboards: { count: DASHBOARDS.length, metricsOnNoDashboard: metricsOnNoDashboard() },
};
writeFileSync(join(RESULTS, "observability.json"), JSON.stringify(payload, null, 2) + "\n");

const L: string[] = [];
L.push("# money-movement-observability results");
L.push("");
L.push("Generated by `scripts/report.ts`. Deterministic: no cloud project, no");
L.push("credentials, no network. Every figure below is a `Simulated result`.");
L.push("");
L.push("## Green on every technical objective, wrong about money");
L.push("");
L.push("Each scenario runs the same instrumented flow with one fault injected.");
L.push("The first column is the one an ordinary monitoring setup would show.");
L.push("");
L.push("| scenario | technical SLOs | invariants violated | alerts fired |");
L.push("|---|---|---|---|");
for (const r of results) {
  const tech = r.technicalGreen ? "all green" : "**breached**";
  const inv = r.invariantsViolated.length ? `**${r.invariantsViolated.join(", ")}**` : "none";
  const alerts = r.alertsFired.length ? r.alertsFired.join(", ") : "none";
  L.push(`| **${r.id}** ${r.title} | ${tech} | ${inv} | ${alerts} |`);
}
L.push("");
L.push(
  `**${greenAndWrong.length} of ${results.length} scenarios leave every technical objective green while a business invariant is violated** ` +
    `(${greenAndWrong.map((r) => r.id).join(", ")}).`,
);
L.push(
  `A further ${greenAndSilent.length} leave every technical objective green with no invariant violated and still page somebody ` +
    `(${greenAndSilent.map((r) => r.id).join(", ")}) — those are the cases where the telemetry itself is the problem.`,
);
L.push("");
L.push("## The headline case, in numbers");
L.push("");
const s04 = results.find((r) => r.id === "S04");
L.push("One payment, one injected fault in the fee branch of the ledger poster.");
L.push("");
L.push("| measured | value |");
L.push("|---|---:|");
L.push(`| HTTP 5xx responses across all four services | ${s04?.extra.httpErrors ?? "n/a"} |`);
for (const t of s04?.technical ?? []) {
  const v = t.value === null ? "n/a" : t.id === "SLO-C2" ? `${t.value} ms` : `${(t.value * 100).toFixed(2)}%`;
  L.push(`| ${t.id} (${t.met ? "met" : "breached"}) | ${v} |`);
}
L.push(`| posting legs written (should be 3) | ${s04?.extra.legs ?? "n/a"} |`);
L.push(`| invariants violated | ${s04?.invariantsViolated.join(", ") || "none"} |`);
L.push("");
L.push("Nothing in the request path noticed. The journal is short by exactly the");
L.push("provider's fee, and the only signal that says so is a check that reads");
L.push("durable state out of band.");
L.push("");
L.push("## Incident: alert, diagnosis, repair, verification");
L.push("");
L.push(`Alert **${evidence.alertId}** routed to \`${evidence.route}\` (${evidence.severity}), runbook \`${evidence.runbook}\`.`);
L.push("");
L.push("| step | value |");
L.push("|---|---|");
L.push(`| violations when the alert fired | ${evidence.violationsBefore} |`);
L.push(`| operation | \`${evidence.diagnosis.operationId}\` |`);
L.push(`| journal | \`${evidence.diagnosis.journalId}\` |`);
L.push(`| money implicated (minor units) | ${evidence.diagnosis.amountMinor} |`);
L.push(`| log query | \`${evidence.diagnosis.logQuery}\` |`);
L.push(`| audit timeline steps available | ${evidence.diagnosis.auditTimeline.length} |`);
L.push(`| repair invoked | ${evidence.repair.timesInvoked} times |`);
L.push(`| second invocation changed anything | ${evidence.repair.idempotent ? "no" : "**yes**"} |`);
L.push(`| violations after verification | ${evidence.violationsAfter} |`);
L.push(`| minutes from alert to verified repair | ${(evidence.verifiedAtMs - evidence.firedAtMs) / 60_000} |`);
L.push(`| outcome | ${evidence.outcome} |`);
L.push("");
L.push("The audit timeline the responder starts from:");
L.push("");
L.push("```text");
for (const line of evidence.diagnosis.auditTimeline) L.push(line);
L.push("```");
L.push("");
L.push("## Synthetic canary");
L.push("");
L.push("A probe payment with a known input and a known expected effect.");
L.push("");
L.push("| check | expected | actual | result |");
L.push("|---|---|---|---|");
for (const c of canary.checks) {
  L.push(`| ${c.name} | ${c.expected} | ${c.actual} | ${c.passed ? "pass" : "**fail**"} |`);
}
L.push("");
L.push(`Canary result: **${canary.passed ? "pass" : "fail"}**.`);
L.push("");
L.push("## Metric cardinality");
L.push("");
L.push("Every label in the catalogue has a closed set of values, so the ceiling");
L.push("on series this system can emit is a number rather than a surprise.");
L.push("");
L.push("| metric | maximum series |");
L.push("|---|---:|");
for (const c of cardinality) L.push(`| \`${c.metric}\` | ${c.series} |`);
L.push(`| **total** | **${totalDeclaredSeries()}** |`);
L.push("");
L.push("## Telemetry volume");
L.push("");
L.push(
  `Illustrative example: ${DEFAULT_ASSUMPTIONS.operationsPerDay.toLocaleString("en-US")} operations per day, ` +
    `traces head-sampled at ${Math.round(DEFAULT_ASSUMPTIONS.traceSamplingRate * 100)}%. ` +
    "No price appears here; multiply by your own.",
);
L.push("");
L.push("| signal | GiB/day | reducible by sampling | note |");
L.push("|---|---:|---|---|");
for (const line of volume.lines) {
  L.push(`| ${line.signal} | ${line.gibPerDay} | ${line.sampleable ? "yes" : "**no**"} | ${line.note} |`);
}
L.push("");
L.push(
  `Of ${volume.totalGibPerDay} GiB/day, ${volume.sampleableGibPerDay} GiB/day can be reduced by sampling and ` +
    `${volume.fixedGibPerDay} GiB/day cannot. The metric line is flat in traffic: ${volume.seriesIndependentOfTraffic} ` +
    "series regardless of how many payments arrive.",
);
L.push("");
L.push("## Negative controls");
L.push("");
L.push("A catalogue written by the same hand as the implementation proves nothing");
L.push("until each scenario has been shown to fail when the mechanism it tests is");
L.push("removed.");
L.push("");
L.push("| mechanism removed | scenarios that turn red | targeted |");
L.push("|---|---|---|");
for (const c of controls) {
  L.push(`| ${c.removed} | ${c.scenariosTurnedRed.join(", ") || "—"} | ${c.targeted ? "yes" : "**no**"} |`);
}
L.push(`| ${bluntControl.removed} | ${bluntControl.scenariosTurnedRed.join(", ")} | **rejected** |`);
L.push("");
L.push(`The blunt mutation is rejected on purpose: ${bluntControl.reason}.`);
L.push("");
L.push("## Alert coverage");
L.push("");
L.push(`Alerts never fired by any scenario: ${neverFired.length ? neverFired.join(", ") : "none"}.`);
L.push(
  `Scenarios that violate an invariant and fire no alert: ${
    scenariosWithoutAlert.length ? scenariosWithoutAlert.join(", ") : "none"
  }.`,
);
L.push("");
L.push(`Invariants not named by any objective: ${invariantsWithoutSlo().join(", ") || "none"}.`);
L.push(`Metrics on no dashboard: ${metricsOnNoDashboard().join(", ") || "none"}.`);
L.push("");
L.push(`Catalogue size: ${INVARIANTS.length} invariants, ${SLOS.length} objectives, ${ALERTS.length} alert rules, ${SCENARIOS.length} scenarios.`);
L.push("");
writeFileSync(join(RESULTS, "report.md"), L.join("\n"));

console.log("wrote results/observability.json and results/report.md");
