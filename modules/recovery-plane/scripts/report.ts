import { writeFileSync } from "node:fs";
import { validate } from "../src/graph.ts";
import { COMPONENTS, DESIGNED_STEPS, NAIVE_STEPS } from "../src/scenarios.ts";

const naive = validate(COMPONENTS, NAIVE_STEPS);
const designed = validate(COMPONENTS, DESIGNED_STEPS);
writeFileSync("results/validation.json", JSON.stringify({ naive, designed }, null, 2));

const rows: string[] = [];
rows.push("# Recovery dependency validation\n");
rows.push("Generated by `make report`. No cloud project, no credentials, no network.\n");
rows.push("Two sets of recovery steps against the same fictional estate.\n");

for (const [name, r] of [["Undesigned", naive], ["Designed against the graph", designed]] as const) {
  rows.push(`## ${name}\n`);
  rows.push(`Findings: **${r.findings.length}**. Safe steps: **${r.safeSteps.length}**.\n`);
  if (r.findings.length === 0) {
    rows.push("No step depends on the domain it repairs.\n");
  } else {
    rows.push("| Step | Repairs | Finding | Dependency chain |");
    rows.push("|---|---|---|---|");
    for (const f of r.findings) {
      rows.push(`| \`${f.stepId}\` | ${f.domain} | ${f.kind} | ${f.path.join(" → ")} |`);
    }
    rows.push("");
  }
}

rows.push("## The shape this reproduces\n");
rows.push("Meta, 5 October 2021: \"the total loss of DNS broke many of the internal");
rows.push("tools we'd normally use to investigate and resolve outages like this\".\n");
rows.push("`restore-dns` reaches its bastion through IAP, and IAP needs DNS. The step");
rows.push("cannot run at the only time it is needed. Nobody designed that; it is a");
rows.push("property of a graph nobody drew.\n");

writeFileSync("results/report.md", rows.join("\n") + "\n");
console.log(rows.join("\n"));
